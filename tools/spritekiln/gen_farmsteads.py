def hip_roof(name, mat, dark, cx, cz, hx, hz, eave, rise, along="x", seed=3):
    """A hipped roof over the rectangle cx +- hx, cz +- hz (overhang included), eaves at
    `eave`, ridge `rise` higher; the ridge runs along `along`. An extruded gable prism with
    its two ends cut off by sloped planes."""
    if along == "x":
        prism = ("extrude: {c: [%.2f, %.2f, %.2f], rot: [0, 1.5708, 0], depth: %.2f, "
                 "profile: {polygon: [[-%.2f, 0], [%.2f, 0], [0, %.2f]]}}" % (cx, eave, cz, 2 * hx, hz, hz, rise))
        k = rise / hz              # the hips as steep as the long slopes
        n = (rise, hz)
        cut = ["plane: {n: [%.3f, %.3f, 0], c: [%.2f, %.2f, %.2f]}" % (n[0], n[1], cx + hx, eave, cz),
               "plane: {n: [-%.3f, %.3f, 0], c: [%.2f, %.2f, %.2f]}" % (n[0], n[1], cx - hx, eave, cz)]
        ridge = "cylinder: {a: [%.2f, %.2f, %.2f], b: [%.2f, %.2f, %.2f], r: 0.1}" % (
            cx - hx + hz, eave + rise - 0.04, cz, cx + hx - hz, eave + rise - 0.04, cz)
    else:
        prism = ("extrude: {c: [%.2f, %.2f, %.2f], depth: %.2f, "
                 "profile: {polygon: [[-%.2f, 0], [%.2f, 0], [0, %.2f]]}}" % (cx, eave, cz, 2 * hz, hx, hx, rise))
        n = (rise, hx)
        cut = ["plane: {n: [0, %.3f, %.3f], c: [%.2f, %.2f, %.2f]}" % (n[1], n[0], cx, eave, cz + hz),
               "plane: {n: [0, %.3f, -%.3f], c: [%.2f, %.2f, %.2f]}" % (n[1], n[0], cx, eave, cz - hz)]
        ridge = "cylinder: {a: [%.2f, %.2f, %.2f], b: [%.2f, %.2f, %.2f], r: 0.1}" % (
            cx, eave + rise - 0.04, cz - hz + hx, cx, eave + rise - 0.04, cz + hz - hx)
    return """  %s:
    material: %s
    prims:
      - %s
    cut:
      - %s
      - %s
    paint:
      - material: %s
        spots: {scale: 0.12, density: 0.26, seed: %d}
  %s_ridge:
    material: %s
    prims:
      - %s
""" % (name, mat, prism, cut[0], cut[1], dark, seed, name, dark, ridge)


