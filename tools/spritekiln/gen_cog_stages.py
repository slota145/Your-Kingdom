"""SpriteKiln: the cog's building stages on the slipway, made from art/specs/props/cog/cog.yaml.

Writes art/specs/props/cog_build_<n>/cog_build_<n>.yaml (8 directions, 1 frame, the same frame and
pivot as the floating cog, so the launch slides build_2 into the water and swaps it for idle):
  0 = keel, stem and sternpost and ribs; 1 = the planked hull with both castles;
  2 = the whole ship (mast, sail, stays, shields, pennant). The hull is out of the water, its flat
  bottom 0.3 below the waterline, on four keel blocks.
Run: python3 tools/spritekiln/gen_cog_stages.py, then `spritekiln render` in each folder and
     python3 tools/spritekiln/export_ship.py cog_build_<n> cog 110,168 --out=build_<n>
"""
import copy
import math
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
PROPS = os.path.join(HERE, "art", "specs", "props")
KEEL = 0.05            # the keel's height in ship space (the ship is sunk 0.35: 0.3 below the water)

RIGGING = ["mast", "yard", "sail", "stays", "pennant", "shields_L"]
CASTLES = ["stern_castle", "merlons", "fore_castle", "rudder"]


def half_beam(z):
    e = max(0.0, abs(z) - 1.9)
    return 1.08 * math.sqrt(max(0.0, 1 - (e / 1.35) ** 2))


def sheer(z):
    return 9.85 - math.sqrt(8.6 ** 2 - z * z)


def r(v):
    return [round(x, 3) for x in v]


def main():
    base = yaml.safe_load(open(os.path.join(PROPS, "cog", "cog.yaml")))
    for stage in range(3):
        s = copy.deepcopy(base)
        s["name"] = f"cog_build_{stage}"
        s["brief"]["summary"] = f"the Your Kingdom cog on the slipway, building stage {stage} of 2, on keel blocks"
        s["animations"] = {"idle": {"frames": 1, "ms": 500, "channels": {}}}
        s["bones"].pop("sailb", None) if stage < 2 else None
        parts = s["parts"]
        parts.pop("foam")
        s["materials"].pop("foam")
        s["materials"].pop("foam_dark")
        s["ramps"].pop("foam")
        parts["hull"]["cut"][0] = {"plane": {"n": [0, -1, 0], "at": -KEEL}}
        parts["blocks"] = {"material": "castle", "prims": [
            {"box": {"c": [0, -0.52, z], "half": [0.55, 0.22, 0.2]}} for z in (-2.4, -0.8, 0.8, 2.4)]}
        if stage < 2:
            for p in RIGGING:
                parts.pop(p, None)
        if stage < 1:
            for p in CASTLES + ["deck"]:
                parts.pop(p, None)
            hull = parts.pop("hull")
            # the bare frame: a keel, the posts and U-shaped ribs following the hull's section
            parts["keel"] = {"material": "castle", "space": "ship",
                             "prims": [{"box": {"c": [0, KEEL + 0.1, 0], "half": [0.12, 0.1, 3.3]}}]}
            ribs = []
            for i in range(11):
                z = -3.0 + 6.0 * i / 10
                hb = half_beam(z) - 0.05
                top = sheer(z) - 0.02
                ribs.append({"tube": {"pts": r_pts([[-hb, top, z], [-hb * 1.02, 0.4, z], [0, KEEL - 0.25, z],
                                                    [hb * 1.02, 0.4, z], [hb, top, z]]), "r": 0.05}})
            parts["ribs"] = {"material": "hull", "space": "ship", "prims": ribs}
            parts["stem"]["material"] = "castle"
        with_dir = os.path.join(PROPS, s["name"])
        os.makedirs(with_dir, exist_ok=True)
        text = yaml.safe_dump(s, sort_keys=False, default_flow_style=None, width=140)
        first, rest = text.split("\n", 1)
        with open(os.path.join(with_dir, s["name"] + ".yaml"), "w") as fh:
            fh.write(first + "\n# Generated by tools/spritekiln/gen_cog_stages.py from cog/cog.yaml.\n" + rest)
        print(s["name"])


def r_pts(pts):
    return [r(p) for p in pts]


if __name__ == "__main__":
    main()
