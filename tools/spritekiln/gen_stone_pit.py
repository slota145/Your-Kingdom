"""The stone pit (E3 part 1): a 3x3 open-cast quarry in a province rich in stone.

A stepped rock outcrop fills the back of the plot: three benches of fresh-cut pale stone, each
face parallel to the plot's front diagonal (game x + y = const), weathered rock and turf on the
top bench, rubble and chips at the foot of the faces. The front of the plot is a dusty yard: a
wooden jib crane on the right with a rope and a hanging block over the lowest bench, a winch
drum with a crank at its foot (the stonecutter at the crane turns it), cut blocks on a sledge,
wedges and a few tools. The entrance tile (game 1, 2) and the strip in front of the faces stay
free: the three stonecutters stand there (data/visuals/buildings/stone_pit.tres, spots face_1..3,
crane).

Game tile (gx, gy) of the 3x3 plot -> model: x = 3.515 - gy * 2.343, z = gx * 2.343 - 3.515
(with directions [se]: +z = game +x, +x = game -y; origin = plot centre).

Writes art/specs/props/stone_pit/stone_pit.yaml; edit this script, not that file.
Run (inside tools/spritekiln): python3 gen_stone_pit.py, then
  cd art/specs/props/stone_pit && spritekiln render stone_pit.yaml
  python3 tools/spritekiln/export_building.py stone_pit     (from the repository root)
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TILE = 2.343
HALF = 1.5 * TILE
R2 = math.sqrt(2.0)


def m(gx, gy, y=0.0):
    """Model point of game tile point (gx, gy) at height y."""
    return [round(HALF - gy * TILE, 3), round(y, 3), round(gx * TILE - HALF, 3)]


def f(v):
    return "[" + ", ".join("%g" % round(c, 3) for c in v) + "]"


def bench(front, height, back=0.0):
    """A box from the plot's back corner to the line game x + y = front, [height] high (its
    faces parallel to the front diagonal), rotated 45 degrees about y."""
    # s: distance from the plot centre towards the back corner along u = (0.707, 0, -0.707).
    s_front = -(front * TILE - 2 * HALF) / R2
    s_back = 2 * HALF / R2 + 0.4 - back
    sc = (s_front + s_back) / 2.0
    hd = (s_back - s_front) / 2.0
    c = [sc / R2, height / 2.0, -sc / R2]
    return "- box: {c: %s, half: [%g, %g, 5.6], rot: [0, 0.7854, 0]}" % (f(c), round(hd, 3), round(height / 2.0, 3))


PLOT_CUTS = """    cut:
      - plane: {n: [1, 0, 0], c: [3.515, 0, 0]}
      - plane: {n: [0, 0, -1], c: [0, 0, -3.515]}
      - plane: {n: [-1, 0, 0], c: [-3.515, 0, 0]}
      - plane: {n: [0, 0, 1], c: [0, 0, 3.515]}"""


def joint(front, t, y0, y1):
    """A dark vertical joint on the face of the bench at game x + y = front, at t (0 = the
    left corner, 1 = the right corner), from height y0 to y1."""
    p = m(front * t, front * (1 - t), (y0 + y1) / 2.0)
    p[0] -= 0.02
    p[2] += 0.02
    return "- box: {c: %s, half: [0.03, %g, 0.035], rot: [0, 0.7854, 0]}" % (f(p), round((y1 - y0) / 2.0, 3))


def course(front, y):
    """A dark horizontal bed joint along the face of the bench at game x + y = front."""
    p = m(front / 2.0, front / 2.0, y)
    p[0] -= 0.02
    p[2] += 0.02
    return "- box: {c: %s, half: [0.03, 0.03, 5.6], rot: [0, 0.7854, 0]}" % f(p)


