"""Standing crops on a field tile (owner 2026-11-11: wheat and hops should stand up from the
field like the vines do): one SpriteKiln spec per crop and growth state, one tile (2.343 x 2.343
units) seen from [se] like the buildings, the tile centre at the model origin.

  grain:  sprout, young, green, ripe          (rows of wheat clumps; nothing while fallow/ploughed)
  hops:   poles, shoot, half, full, ripe       (two tall poles, a top wire, two strings per tile,
                                                bines climbing the strings, cones when ripe)

Writes art/specs/props/crop_<crop>_<state>/crop_<crop>_<state>.yaml; edit this script.
Run (inside tools/spritekiln): python3 gen_crops.py, then
  for d in art/specs/props/crop_*; do (cd $d && spritekiln render $(basename $d).yaml); done
  python3 tools/spritekiln/export_crops.py      (from the repository root)
"""
