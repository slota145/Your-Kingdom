  ear_g:  ['#1a2a0a', '#34501a', '#4e6e22', '#6c8c2e', '#8ca63c', '#aec05a']
  gold:   ['#2a1a06', '#5a3e10', '#8a6418', '#b88c24', '#d8b040', '#f0d070']
  straw:  ['#2a1c08', '#5a4416', '#86682a', '#a8863c', '#c8a650', '#e0c46c']
  leaf:   ['#0e1e08', '#1c3a0e', '#2c5414', '#3e6e1c', '#548a26', '#6ea434']
