TAIL = """
animations:
  idle:
    frames: 1
    ms: 500
    channels: {}
"""

HALF = 1.05          # plants stay inside the tile (half 1.17)


def clumps(seed):
    """Wheat clump spots: 4 rows across the tile (along model z), 5 clumps each, jittered."""
    rnd = random.Random(seed)
    spots = []
    for i in range(4):
        x = -HALF + (i + 0.5) * 2 * HALF / 4
        for j in range(5):
            z = -HALF + (j + 0.5) * 2 * HALF / 5
            spots.append((x + rnd.uniform(-0.07, 0.07), z + rnd.uniform(-0.07, 0.07), rnd.random()))
    return spots


def grain(state):
    """(parts text, frame size, camera centre y) of wheat in [state]."""
    h, w, stalk_mat, ear_mat, ears, droop = {
        "sprout": (0.26, 0.045, "sprout", None, False, 0.0),
        "young": (0.6, 0.05, "stalk", None, False, 0.0),
        "green": (0.95, 0.05, "stalk", "ear_g", True, 0.05),
        "ripe": (0.95, 0.05, "straw", "gold", True, 0.16),
    }[state]
    stalks, heads = [], []
    for x, z, r in clumps(7):
        for k in range(3):
            a = (k / 3.0 + r) * math.tau
            lean = 0.06 + 0.04 * k
            top = h * (0.85 + 0.15 * ((k + int(r * 10)) % 3) / 2)
            bx, bz = x + 0.05 * math.cos(a), z + 0.05 * math.sin(a)
            tx, tz = bx + lean * math.cos(a) + droop, bz + lean * math.sin(a)
            stalks.append("      - cone: {a: [%.3f, 0.0, %.3f], b: [%.3f, %.3f, %.3f], r: [%.3f, %.3f]}"
                          % (bx, bz, tx, top, tz, w, w * 0.6))
            if ears:
                heads.append("      - ellipsoid: {c: [%.3f, %.3f, %.3f], r: [0.05, 0.11, 0.05], rot: [0, 0, %.3f]}"
                             % (tx + droop * 0.6, top + 0.06 - droop * 0.5, tz, -droop * 4.0))
    parts = "  stalks:\n    material: %s\n    min_cover: 2\n    prims:\n%s\n" % (stalk_mat, "\n".join(stalks))
    if heads:
        parts += "  ears:\n    material: %s\n    min_cover: 2\n    priority: 2\n    prims:\n%s\n" % (ear_mat, "\n".join(heads))
    return parts, 96, 0.55


POLE_H = 2.7
POLES = [(-1.08, 0.0), (1.08, 0.0)]          # along model x: rows of poles across the field
STRINGS = [(-0.45, -0.4), (0.45, 0.4)]    # where two strings leave the ground (x, z): side by side on screen


def hops(state):
    parts = ["  poles:\n    material: post\n    prims:\n" + "\n".join(
        "      - cylinder: {a: [%.2f, 0.0, %.2f], b: [%.2f, %.2f, %.2f], r: 0.06}" % (x, z, x, POLE_H, z)
        for x, z in POLES) + "\n",
        "  wire:\n    material: wire\n    min_cover: 1\n    priority: 2\n    prims:\n"
        "      - cylinder: {a: [-1.08, %.2f, 0.0], b: [1.08, %.2f, 0.0], r: 0.02}\n" % (POLE_H - 0.08, POLE_H - 0.08),
        "  strings:\n    material: twine\n    min_cover: 1\n    priority: 2\n    prims:\n" + "\n".join(
            "      - cylinder: {a: [%.2f, 0.0, %.2f], b: [%.2f, %.2f, 0.0], r: 0.018}" % (x, z, x * 0.6, POLE_H - 0.1)
            for x, z in STRINGS) + "\n"]
    reach = {"poles": 0.0, "shoot": 0.35, "half": 1.35, "full": POLE_H - 0.15, "ripe": POLE_H - 0.15}[state]
    if reach > 0.0:
        rnd = random.Random(11)
        leaves, cones = [], []
        for x, z in STRINGS:
            top = (x * 0.6, POLE_H - 0.1, 0.0)
            n = max(int(reach / 0.16), 2)
            for i in range(n):
                t = (i + 0.5) / n * reach / (POLE_H - 0.1)
                px, py, pz = x + (top[0] - x) * t, top[1] * t, z + (top[2] - z) * t
                s = 0.115 if state != "shoot" else 0.09
                for k in range(2):
                    a = rnd.random() * math.tau
                    leaves.append("      - ellipsoid: {c: [%.3f, %.3f, %.3f], r: [%.3f, %.3f, %.3f]}"
                                  % (px + 0.08 * math.cos(a), py + 0.04, pz + 0.08 * math.sin(a), s, s * 0.75, s))
                if state == "ripe" and py > 0.5:
                    a = rnd.random() * math.tau
                    cones.append("      - ellipsoid: {c: [%.3f, %.3f, %.3f], r: [0.07, 0.1, 0.07]}"
                                 % (px + 0.13 * math.cos(a), py - 0.05, pz + 0.13 * math.sin(a)))
        parts.append("  bines:\n    material: leaf\n    blend: 0.03\n    prims:\n" + "\n".join(leaves) + "\n")
        if cones:
            parts.append("  cones:\n    material: cone\n    priority: 2\n    prims:\n" + "\n".join(cones) + "\n")
    return "".join(parts), 128, 1.6


CROPS = {
    "grain": (grain, ["sprout", "young", "green", "ripe"], "none",
              "Your Kingdom wheat on one field tile, {state}: rows of wheat clumps"),
    "hops": (hops, ["poles", "shoot", "half", "full", "ripe"], "dark",
             "Your Kingdom hop garden on one field tile, {state}: two tall poles with a top wire, two strings, bines climbing them"),
}


def main():
    for crop, (make, states, outline, summary) in CROPS.items():
        for state in states:
            name = "crop_%s_%s" % (crop, state)
            parts, size, cy = make(state)
            d = os.path.join(HERE, "art", "specs", "props", name)
            os.makedirs(d, exist_ok=True)
            with open(os.path.join(d, name + ".yaml"), "w") as f:
                f.write(HEAD.format(name=name, outline=outline, size=size, cy=cy,
                                    summary=summary.format(state=state)) + parts + TAIL)
            print("written", name)


if __name__ == "__main__":
    main()
